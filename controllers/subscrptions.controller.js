const {
  ref,
  set,
  get,
  update,
  remove,
  query,
  orderByChild,
  equalTo,
} = require("firebase/database");
const { database } = require("../firebaseConfig.js");
const { v4: uuidv4 } = require("uuid");

const toISODate = (date = new Date()) => new Date(date).toISOString().slice(0, 10);

function calculateEndDateByDays(startDate, days) {
  const start = new Date(startDate);
  const end = new Date(start);
  end.setDate(end.getDate() + Number(days || 0));
  return toISODate(end);
}

const asNumber = (value, fallback = 0) => {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
};

const normalizeCurrency = (currency, fallback = "SYP") => {
  if (typeof currency !== "string") return fallback;
  const trimmed = currency.trim().toUpperCase();
  return trimmed || fallback;
};

const parseDate = (dateString) => {
  const parsed = new Date(dateString);
  return Number.isNaN(parsed.getTime()) ? new Date() : parsed;
};

const getPlanMap = async () => {
  const plansSnap = await get(ref(database, "subscriptionPlans"));
  return plansSnap.val() || {};
};

const normalizeSubscription = (sub = {}) => {
  const expectedAmount = asNumber(sub.expectedAmount, asNumber(sub.amount, 0));
  const amountPaid = asNumber(sub.amountPaid, 0);
  const carryIn = asNumber(sub.carryIn, 0);
  const carryOut = asNumber(sub.carryOut, carryIn + expectedAmount - amountPaid);
  const remaining = expectedAmount - amountPaid;

  let status = sub.status || sub.paymentStatus || "unpaid";
  if (!sub.status && !sub.paymentStatus) {
    if (remaining < 0) status = "overpaid";
    else if (remaining === 0) status = "paid";
    else if (amountPaid > 0) status = "partial";
    else status = "unpaid";
  }

  return {
    ...sub,
    expectedAmount,
    amount: expectedAmount,
    amountPaid,
    carryIn,
    carryOut,
    currency: normalizeCurrency(sub.currency),
    planKey: sub.planKey || "",
    cycleIndex: asNumber(sub.cycleIndex, 1),
    status,
    paymentStatus: status,
    createdAt: sub.createdAt || new Date().toISOString(),
  };
};

const ensureSubscriptionReadAccess = (req, res, subscription) => {
  if (req.user?.type === "admin") return true;
  if (subscription.userId !== req.userId) {
    res.status(403).json({ message: "Access denied" });
    return false;
  }
  return true;
};

const getUserSubscriptions = async (userId) => {
  const snapshot = await get(query(ref(database, "subscriptions"), orderByChild("userId"), equalTo(userId)));
  const raw = snapshot.val() || {};
  return Object.values(raw)
    .map((entry) => normalizeSubscription(entry))
    .sort((a, b) => parseDate(a.startDate).getTime() - parseDate(b.startDate).getTime());
};

const saveUserBillingSummary = async (userId, summary) => {
  await set(ref(database, `userBilling/${userId}`), {
    ...summary,
    lastUpdatedAt: new Date().toISOString(),
  });
};

const buildUserSummary = (userId, subscriptions = []) => {
  const totalExpected = subscriptions.reduce((sum, sub) => sum + asNumber(sub.expectedAmount), 0);
  const totalPaid = subscriptions.reduce((sum, sub) => sum + asNumber(sub.amountPaid), 0);
  const walletBalance = totalExpected - totalPaid;

  const currentCycle = [...subscriptions]
    .sort((a, b) => parseDate(b.startDate).getTime() - parseDate(a.startDate).getTime())
    .find((sub) => !sub.nextCycleId) || null;

  return {
    userId,
    activeSubscriptionId: currentCycle?.id || null,
    walletBalance,
    totalExpected,
    totalPaid,
    totalRemaining: walletBalance,
    cycleCount: subscriptions.length,
    currentCycle,
  };
};

const refreshUserSummary = async (userId) => {
  const subscriptions = await getUserSubscriptions(userId);
  const summary = buildUserSummary(userId, subscriptions);
  await saveUserBillingSummary(userId, summary);
  return summary;
};

const createNextCycle = ({ previousSub, plan, autoGenerated }) => {
  const previous = normalizeSubscription(previousSub);
  const startDate = toISODate(new Date());
  const endDate = calculateEndDateByDays(startDate, asNumber(plan.duration, 0));

  const id = uuidv4();
  const expectedAmount = asNumber(plan.price, previous.expectedAmount);
  const carryIn = asNumber(previous.carryOut, 0);

  return {
    id,
    userId: previous.userId,
    planKey: previous.planKey || plan.key || "",
    planName: plan.name || previous.planName,
    currency: normalizeCurrency(previous.currency || plan.currency),
    startDate,
    endDate,
    cycleIndex: asNumber(previous.cycleIndex, 1) + 1,
    previousCycleId: previous.id,
    nextCycleId: null,
    expectedAmount,
    amount: expectedAmount,
    amountPaid: 0,
    carryIn,
    carryOut: carryIn + expectedAmount,
    status: carryIn + expectedAmount === 0 ? "paid" : "unpaid",
    paymentStatus: carryIn + expectedAmount === 0 ? "paid" : "unpaid",
    autoGenerated,
    createdAt: new Date().toISOString(),
  };
};

const createSubscription = async (req, res) => {
  try {
    const { userId, planKey, startDate, currency } = req.body;
    if (!userId || !planKey) return res.status(400).json({ message: "Missing data" });

    const plans = await getPlanMap();
    const plan = plans?.[planKey];
    if (!plan) return res.status(400).json({ message: "Invalid plan" });

    const start = toISODate(startDate ? parseDate(startDate) : new Date());
    const end = calculateEndDateByDays(start, asNumber(plan.duration, 0));

    const subId = uuidv4();
    const expectedAmount = asNumber(plan.price, 0);

    const newSub = normalizeSubscription({
      id: subId,
      userId,
      planKey,
      planName: plan.name || planKey,
      currency: normalizeCurrency(currency || plan.currency),
      startDate: start,
      endDate: end,
      cycleIndex: 1,
      previousCycleId: null,
      nextCycleId: null,
      expectedAmount,
      amount: expectedAmount,
      amountPaid: 0,
      carryIn: 0,
      carryOut: expectedAmount,
      status: "unpaid",
      paymentStatus: "unpaid",
      autoGenerated: false,
      createdAt: new Date().toISOString(),
    });

    await set(ref(database, `subscriptions/${subId}`), newSub);
    await update(ref(database, `users/${userId}`), { currentSubscriptionId: subId });

    const summary = await refreshUserSummary(userId);
    return res.status(201).json({ subscription: newSub, summary });
  } catch (err) {
    console.error("createSubscription failed:", err);
    return res.status(500).json({ message: "Error creating subscription" });
  }
};

const getAllSubscriptions = async (_, res) => {
  try {
    const snapshot = await get(ref(database, "subscriptions"));
    const raw = snapshot.val() || {};
    const normalized = Object.entries(raw).reduce((acc, [id, item]) => {
      acc[id] = normalizeSubscription(item);
      return acc;
    }, {});

    return res.status(200).json(normalized);
  } catch (err) {
    return res.status(500).json({ message: "Error fetching subscriptions" });
  }
};

const getSubscriptionsByUser = async (req, res) => {
  try {
    const { userId } = req.params;
    const subs = await getUserSubscriptions(userId);

    const result = subs.reduce((acc, sub) => {
      acc[sub.id] = sub;
      return acc;
    }, {});

    return res.status(200).json(result);
  } catch (err) {
    return res.status(500).json({ message: "Error fetching user subscriptions" });
  }
};

const addPayment = async (req, res) => {
  try {
    const { subId } = req.params;
    const { amount, method, note, currency } = req.body;

    const amountValue = asNumber(amount, 0);
    if (amountValue <= 0 || !method) {
      return res.status(400).json({ message: "Missing payment data" });
    }

    const subSnap = await get(ref(database, `subscriptions/${subId}`));
    if (!subSnap.exists()) return res.status(404).json({ message: "Subscription not found" });

    const sub = normalizeSubscription(subSnap.val());
    const paymentId = uuidv4();

    const payment = {
      id: paymentId,
      subId,
      paymentDate: toISODate(),
      amount: amountValue,
      currency: normalizeCurrency(currency || sub.currency),
      method,
      note: note || "",
      createdBy: req.userId,
      createdAt: new Date().toISOString(),
    };

    await set(ref(database, `payments/${subId}/${paymentId}`), payment);

    const newAmountPaid = sub.amountPaid + amountValue;
    const carryOut = sub.carryIn + sub.expectedAmount - newAmountPaid;

    let status = "unpaid";
    if (carryOut < 0) status = "overpaid";
    else if (carryOut === 0) status = "paid";
    else if (newAmountPaid > 0) status = "partial";

    const updatedSub = {
      amountPaid: newAmountPaid,
      carryOut,
      status,
      paymentStatus: status,
      updatedAt: new Date().toISOString(),
    };

    await update(ref(database, `subscriptions/${subId}`), updatedSub);
    const summary = await refreshUserSummary(sub.userId);

    return res.status(200).json({ success: true, payment, subscription: { ...sub, ...updatedSub }, summary });
  } catch (err) {
    console.error("addPayment failed:", err);
    return res.status(500).json({ message: "Error adding payment" });
  }
};

const getSubscriptionPayments = async (req, res) => {
  try {
    const { subId } = req.params;

    const subSnap = await get(ref(database, `subscriptions/${subId}`));
    if (!subSnap.exists()) return res.status(404).json({ message: "Subscription not found" });

    const sub = normalizeSubscription(subSnap.val());
    if (!ensureSubscriptionReadAccess(req, res, sub)) return;

    const paymentsSnap = await get(ref(database, `payments/${subId}`));
    const paymentsMap = paymentsSnap.val() || {};

    const payments = Object.values(paymentsMap).sort(
      (a, b) => parseDate(a.paymentDate).getTime() - parseDate(b.paymentDate).getTime()
    );

    return res.status(200).json({ subscription: sub, payments });
  } catch (err) {
    return res.status(500).json({ message: "Error fetching payments" });
  }
};

const renewSubscription = async (req, res) => {
  try {
    const { subId } = req.params;

    const subSnap = await get(ref(database, `subscriptions/${subId}`));
    if (!subSnap.exists()) return res.status(404).json({ message: "Subscription not found" });

    const currentSub = normalizeSubscription(subSnap.val());
    if (currentSub.nextCycleId) {
      return res.status(409).json({ message: "Next cycle already exists", nextCycleId: currentSub.nextCycleId });
    }

    const plans = await getPlanMap();
    const plan = plans[currentSub.planKey] || Object.values(plans).find((item) => item?.name === currentSub.planName);
    if (!plan) return res.status(400).json({ message: "Plan not found for renewal" });

    const nextCycle = createNextCycle({
      previousSub: currentSub,
      plan: { ...plan, key: currentSub.planKey || "" },
      autoGenerated: false,
    });

    await set(ref(database, `subscriptions/${nextCycle.id}`), nextCycle);
    await update(ref(database, `subscriptions/${subId}`), {
      nextCycleId: nextCycle.id,
      status: "closed",
      paymentStatus: "closed",
      updatedAt: new Date().toISOString(),
    });

    await update(ref(database, `users/${currentSub.userId}`), { currentSubscriptionId: nextCycle.id });

    const summary = await refreshUserSummary(currentSub.userId);
    return res.status(201).json({ success: true, previous: currentSub.id, nextCycle, summary });
  } catch (err) {
    console.error("renewSubscription failed:", err);
    return res.status(500).json({ message: "Error renewing subscription" });
  }
};

const deleteSubscription = async (req, res) => {
  try {
    const { subId } = req.params;
    const subSnap = await get(ref(database, `subscriptions/${subId}`));

    if (subSnap.exists()) {
      const sub = normalizeSubscription(subSnap.val());

      if (sub.previousCycleId) {
        await update(ref(database, `subscriptions/${sub.previousCycleId}`), { nextCycleId: null });
      }
      if (sub.nextCycleId) {
        await update(ref(database, `subscriptions/${sub.nextCycleId}`), { previousCycleId: null });
      }

      await remove(ref(database, `subscriptions/${subId}`));
      await remove(ref(database, `payments/${subId}`));

      const userRef = ref(database, `users/${sub.userId}`);
      const userSnap = await get(userRef);
      if (userSnap.exists()) {
        const user = userSnap.val();
        if (user.currentSubscriptionId === subId) {
          await update(userRef, { currentSubscriptionId: sub.previousCycleId || null });
        }
      }

      await refreshUserSummary(sub.userId);
    }

    return res.status(200).json({ success: true, message: "Subscription deleted" });
  } catch (err) {
    return res.status(500).json({ message: "Error deleting subscription" });
  }
};

