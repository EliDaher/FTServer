const getAllBillingSummary = async (_, res) => {
  try {
    const [subsSnap, usersSnap] = await Promise.all([
      get(ref(database, "subscriptions")),
      get(ref(database, "users")),
    ]);

    const subscriptions = Object.values(subsSnap.val() || {}).map((item) => normalizeSubscription(item));
    const users = usersSnap.val() || {};

    const grouped = subscriptions.reduce((acc, sub) => {
      const userId = sub.userId;
      if (!acc[userId]) {
        acc[userId] = {
          userId,
          fullname: users[userId]?.fullname || userId,
          username: users[userId]?.username || userId,
          walletBalance: 0,
          totalExpected: 0,
          totalPaid: 0,
          cycles: [],
        };
      }

      acc[userId].totalExpected += sub.expectedAmount;
      acc[userId].totalPaid += sub.amountPaid;
      acc[userId].walletBalance = acc[userId].totalExpected - acc[userId].totalPaid;
      acc[userId].cycles.push(sub);
      return acc;
    }, {});

    return res.status(200).json(Object.values(grouped));
  } catch (error) {
    console.error("getAllBillingSummary failed:", error);
    return res.status(500).json({ message: "Failed to get billing summary" });
  }
};

const runDailyCycleGeneration = async () => {
  const today = toISODate();

  try {
    const [subsSnap, plansSnap] = await Promise.all([
      get(ref(database, "subscriptions")),
      get(ref(database, "subscriptionPlans")),
    ]);

    const subscriptionsMap = subsSnap.val() || {};
    const plansMap = plansSnap.val() || {};

    for (const rawSub of Object.values(subscriptionsMap)) {
      const sub = normalizeSubscription(rawSub);
      if (sub.nextCycleId) continue;
      if (!sub.endDate || sub.endDate >= today) continue;

      const plan = plansMap[sub.planKey] || Object.values(plansMap).find((item) => item?.name === sub.planName);
      if (!plan) continue;

      const nextCycle = createNextCycle({
        previousSub: sub,
        plan: { ...plan, key: sub.planKey || "" },
        autoGenerated: true,
      });

      await set(ref(database, `subscriptions/${nextCycle.id}`), nextCycle);
      await update(ref(database, `subscriptions/${sub.id}`), {
        nextCycleId: nextCycle.id,
        status: "closed",
        paymentStatus: "closed",
        updatedAt: new Date().toISOString(),
      });
      await update(ref(database, `users/${sub.userId}`), { currentSubscriptionId: nextCycle.id });
      await refreshUserSummary(sub.userId);
    }
  } catch (error) {
    console.error("runDailyCycleGeneration failed:", error);
  }
};

